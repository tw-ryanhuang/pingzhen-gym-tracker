import assert from 'node:assert/strict';
import {DatabaseSync} from 'node:sqlite';
import {EFFECTIVE_SAMPLES,displaySample} from '../src/readings.js';
const db=new DatabaseSync(':memory:');
db.exec(`CREATE TABLE samples(slot TEXT PRIMARY KEY,fetched_at TEXT,local_date TEXT,weekday INTEGER,hour INTEGER,minute INTEGER,count INTEGER,status TEXT,detail TEXT);`);
const first='2026-11-11T23:59:50.000Z';
const detail=(count,at='2026-11-12T00:00:10.000Z',status='ok')=>JSON.stringify({kind:'zero_recheck',retry:{count,at,status}});
const add=(id,count,status,raw)=>db.prepare('INSERT INTO samples VALUES(?,?,?,?,?,?,?,?,?)').run(id,first,'2026-11-12',4,7,15,count,status,raw);
add('recovered',0,'zero_unverified',detail(19));
add('normal',21,'ok',null);
add('zero',0,'zero_unverified',detail(0));
add('failed',0,'zero_unverified',detail(19,undefined,'error'));
add('malformed',0,'zero_unverified','{oops');
add('too-late',0,'zero_unverified',detail(19,'2026-11-12T00:04:50Z'));
add('negative',0,'zero_unverified',detail(-1));
add('string',0,'zero_unverified',detail('19'));
add('fraction',0,'zero_unverified',detail(1.5));
add('oversize',0,'zero_unverified',detail(5001));
add('before-first',0,'zero_unverified',detail(19,'2026-11-11T23:59:40Z'));
add('observation',0,'observation',detail(19));
const rows=db.prepare(EFFECTIVE_SAMPLES+' SELECT * FROM effective_samples').all();
const accepted=rows.filter(r=>r.effective_status==='ok');assert.equal(accepted.length,2);
const recovered=displaySample(rows.find(r=>r.slot==='recovered'));
assert.equal(recovered.count,19);assert.equal(recovered.raw_count,0);assert.equal(recovered.status,'ok');assert.equal(recovered.raw_status,'zero_unverified');assert(recovered.rechecked);
const mean=db.prepare(EFFECTIVE_SAMPLES+" SELECT COUNT(*) AS n,AVG(effective_count) AS mean FROM effective_samples WHERE effective_status='ok'").get();
assert.equal(mean.n,2);assert.equal(mean.mean,20);
assert.equal(db.prepare("SELECT count FROM samples WHERE slot='recovered'").get().count,0);
console.log('PASS: recovered retry counted once, raw zero preserved, invalid/late/zero/observation retries excluded');
